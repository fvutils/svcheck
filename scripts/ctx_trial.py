#!/usr/bin/env python3
"""Runs the contexts trial (svcheck-plan P1.6b; sv-contexts.md §6.1): the
three rules of `rules/trial/contexts.yaml` with each classifier set, content
only and content plus convention, on each corpus of `tests/corpora/`, and
prints what each set decided, as Markdown.

    scripts/ctx_trial.py [--svcheck BIN] [--raw DIR] [CORPUS ...]

CORPUS is a `tests/corpora/<name>.f` (default: the three of the trial and
P1.7's positive corpus). For each corpus and set it prints the labels on
each package and definition (a class's are summed into its package, Q-CX3)
with where they came from, how
the two sets differ, the notes where a weaker source disagreed (Q-CX4), the
units with more than one carrier (Q-CX5), and the three rules' findings.
`--raw` keeps svcheck's JSON output there.
"""
import argparse
import json
import os
import re
import subprocess
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CORPORA = ["uvm-tb-proto", "fw-wb-dma", "opentitan-uart", "ctx-positive"]
# Relative to ROOT, where svcheck runs, so evidence names them that way.
RULES = "rules/trial/contexts.yaml"
SETS = {
    "content": [RULES],
    "convention": [RULES, "rules/trial/classify-convention.yaml"],
}
# "unit agent: Content (rules/trial/classify-content.yaml:15) on Class x"
EVIDENCE = re.compile(r"^(\S+) (\S+): (\w+) \((.*?)\) on (\w+) (\S+)$")


def run(svcheck, corpus, rules, extra):
    cmd = [svcheck]
    for r in rules:
        cmd += ["--rules", r]
    cmd += ["-F", "tests/corpora/%s.f" % corpus, "--format", "json"]
    t0 = time.perf_counter()
    p = subprocess.run(cmd + extra, capture_output=True, text=True, cwd=ROOT)
    dt = time.perf_counter() - t0
    if p.returncode not in (0, 1) or not p.stdout.strip():
        sys.exit("svcheck failed (%d) on %s:\n%s" % (p.returncode, corpus, p.stderr))
    return json.loads(p.stdout), dt


def carriers(ctx):
    """{(kind, name): {label: source}} for packages and definitions."""
    out = {}
    for u in ctx["units"]:
        for e in u["evidence"]:
            m = EVIDENCE.match(e)
            if not m:
                continue
            _axis, label, source, _where, kind, name = m.groups()
            if kind == "Class":
                continue
            out.setdefault((kind, name), {}).setdefault(label, source)
    return out


def fmt_labels(ls):
    return ", ".join("%s (%s)" % (l, s.lower()) for l, s in sorted(ls.items())) or "—"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--svcheck", default=os.path.join(ROOT, "python", "svcheck", "bin", "svcheck"))
    ap.add_argument("--raw", help="a directory to keep svcheck's JSON in")
    ap.add_argument("corpora", nargs="*", default=CORPORA)
    args = ap.parse_args()

    print("# Contexts trial: results\n")
    print("Generated by `scripts/ctx_trial.py` (svcheck-plan P1.6b).\n")
    for corpus in args.corpora:
        res = {}
        for name, rules in SETS.items():
            ctx, t_ctx = run(args.svcheck, corpus, rules, ["--contexts"])
            lint, t_lint = run(args.svcheck, corpus, rules, [])
            res[name] = (ctx, lint, t_ctx, t_lint)
            if args.raw:
                os.makedirs(args.raw, exist_ok=True)
                for what, doc in (("contexts", ctx), ("lint", lint)):
                    with open(os.path.join(args.raw, "%s.%s.%s.json" % (corpus, name, what)),
                              "w") as fp:
                        json.dump(doc, fp, indent=1)

        print("## %s\n" % corpus)
        lint0 = res["content"][1]
        print("%d files; compilation errors: %d. Wall time, `--contexts` / lint: %s.\n" % (
            len(lint0["compilation"]["files"]), lint0["compilation"]["errors"],
            "; ".join("%s %.2f s / %.2f s" % (n, r[2], r[3]) for n, r in res.items())))

        c = {n: carriers(r[0]) for n, r in res.items()}
        keys = sorted(set(c["content"]) | set(c["convention"]), key=lambda k: (k[0], k[1]))
        print("### Labels on packages and definitions\n")
        print("| Carrier | Content only | Content + convention |")
        print("|---|---|---|")
        for k in keys:
            a, b = c["content"].get(k, {}), c["convention"].get(k, {})
            mark = "" if set(a) == set(b) else " **≠**"
            print("| %s `%s` | %s | %s%s |" % (k[0], k[1], fmt_labels(a), fmt_labels(b), mark))
        nclass = {n: sum(1 for u in r[0]["units"] for e in u["evidence"] if " on Class " in e)
                  for n, r in res.items()}
        print("\nClass labels: %s.\n" % ", ".join("%s %d" % kv for kv in nclass.items()))

        print("### Notes (a weaker source disagreed)\n")
        any_note = False
        for n, r in res.items():
            for note in r[0]["notes"]:
                any_note = True
                print("- %s: `%s` %s" % (n, note["where"], note["message"]))
        if not any_note:
            print("None, with either set.")
        print()

        print("### Units of more than one carrier\n")
        multi = [(n, u) for n, r in res.items() for u in r[0]["units"]
                 if len(u["carriers"]) > 1]
        if not multi:
            print("None, with either set.")
        for n, u in multi:
            print("- %s: `%s` = %s" % (n, u["name"], ", ".join(
                "%s `%s`" % (x["kind"], x["name"]) for x in u["carriers"])))
        print()

        print("### Findings\n")
        print("| Rule | Content only | Content + convention |")
        print("|---|---|---|")
        f = {n: r[1]["findings"] for n, r in res.items()}
        stats = {n: {s["id"]: s for s in r[1]["rules"]} for n, r in res.items()}
        for rid in ("CTX001", "CTX002", "CTX003"):
            cells = []
            for n in SETS:
                k = sum(1 for x in f[n] if x["code"] == rid)
                s = stats[n].get(rid, {})
                extra = ""
                if s.get("outside") or s.get("unknown"):
                    extra = " (skipped: %d outside, %d unknown)" % (s.get("outside", 0),
                                                                   s.get("unknown", 0))
                cells.append("%d%s" % (k, extra))
            print("| %s | %s |" % (rid, " | ".join(cells)))
        print()
        for n in SETS:
            for x in f[n]:
                if x["code"].startswith("CTX"):
                    print("- %s: `%s:%d` %s: %s" % (n, os.path.relpath(x["file"], ".")
                          if x["file"] else "", x["line"], x["code"], x["message"]))
        others = sorted({x["code"] for n in SETS for x in f[n] if not x["code"].startswith("CTX")})
        if others:
            print("- other markers: %s" % ", ".join(others))
        print()


if __name__ == "__main__":
    main()
