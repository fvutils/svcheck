#!/usr/bin/env python3
"""Generate the svcheck-rules agent skill's reference files
(skills/svcheck-rules/references/), which must not drift from svcheck:

- ``model.md``: every class, field and enum of the curated model, from
  ``src/ast/*.yaml``, with each field's type as the rule checker gives it;
- ``functions.md``: every function a rule can call, from the registry;
- ``uvm-helpers.md``: the helpers of the built-in ``rules/uvm.yaml``, which a
  rule file reads with ``uses: [uvm.yaml]``;
- ``syntax-kinds.md``: slang's syntax types, their kinds and fields, from
  ``packages/slang/scripts/syntax.txt``.

The types and the functions are read through ``svcheck --engine-test-hooks
--semantic=model`` (python/svcheck/bin/svcheck), so build and install first.
Run after changing the model, a library function, rules/uvm.yaml or slang;
``tests/host/test_skills.py`` fails when a committed file is stale.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_ROOT / "tests" / "engine"))
sys.path.insert(0, str(_ROOT / "scripts"))

OUT_DIR = _ROOT / "skills" / "svcheck-rules" / "references"
AST_DIR = _ROOT / "src" / "ast"
UVM_YAML = _ROOT / "rules" / "uvm.yaml"
SYNTAX_TXT = _ROOT / "packages" / "slang" / "scripts" / "syntax.txt"
#: The model's files, in reading order; any other is appended.
AST_ORDER = ["core", "unit", "decl", "type", "stmt", "expr"]

_GENERATED = ("<!-- GENERATED by scripts/gen_skill_refs.py from %s. Do not edit; "
              "rerun the script. -->\n\n")

# A reference to svcheck's design documents, which are not published: the
# skill's reader cannot follow one, so `_public` takes them out of the text.
_REF = re.compile(r"sv-[a-z-]+\.md(\s*§[\d.]+)?|svcheck-(plan|design)(\s*§[\d.]+)?|"
                  r"Q-[A-Z]+\d+('s starting point)?|\bS-\d+\b|\bP\d+\.\d+[a-z]?\b|"
                  r"\bP\d+-\d+\b|\bR-\d+\b")


def _public(text):
    """`text` without its references to the design documents."""
    def paren(m):
        parts = []
        for p in m.group(1).split(";"):
            p = _REF.sub("", p).strip(" ,:")
            if p:
                parts.append(p)
        return " (%s)" % "; ".join(parts) if parts else ""
    text = re.sub(r"\s*\(([^()]*)\)", lambda m: paren(m) if _REF.search(m.group(1))
                  else m.group(0), text)
    return text


# ---------------------------------------------------------------------------
# model.md
# ---------------------------------------------------------------------------

def _ast_files():
    files = {p.stem: p for p in AST_DIR.glob("*.yaml")}
    return [files[n] for n in AST_ORDER if n in files] + \
        [files[n] for n in sorted(files) if n not in AST_ORDER]


def _split_doc(doc):
    """A class doc as (description, {attribute: text})."""
    desc, attrs, cur, in_attrs = [], {}, None, False
    for line in (doc or "").splitlines():
        if line.strip() == "Attributes:":
            in_attrs = True
            continue
        if not in_attrs:
            desc.append(line.strip())
            continue
        m = re.match(r"\s*(\w+): (.*)$", line)
        if m:
            cur = m.group(1)
            attrs[cur] = m.group(2).strip()
        elif cur and line.strip():
            attrs[cur] += " " + line.strip()
    text = " ".join(x for x in desc if x)
    return _public(text), {k: _public(v) for k, v in attrs.items()}


def _model():
    """[(file stem, {"enums": [...], "classes": [...], "structs": [...]})]."""
    out = []
    for p in _ast_files():
        with open(p, encoding="utf-8") as f:
            out.append((p.stem, yaml.safe_load(f) or {}))
    return out


def _entries(section):
    for item in section or []:
        (name, body), = item.items()
        yield name, body or {}


def _fields(body):
    for item in body.get("data") or []:
        (name, spec), = item.items()
        yield name, spec or {}


def field_types(hooks, model):
    """{(class, field): type the rule checker gives, or None if unreadable}."""
    out = {}
    for _, sec in model:
        for cls, body in _entries(sec.get("classes")):
            for fld, _ in _fields(body):
                expr = "descendants(node).filter(d, type(d) == %s).map(d, d.%s)" % (cls, fld)
                r = hooks.cel_check_node({"expr": expr}, "module m; endmodule\n")
                t = None
                if not r["errors"]:
                    t = r["types"]["expr"]
                    t = t[len("list("):-1]
                out[(cls, fld)] = t
    return out


def render_model(model, types) -> str:
    enums = {n for _, sec in model for n, _ in _entries(sec.get("enums"))}
    supers = {n: b.get("super") for _, sec in model for n, b in _entries(sec.get("classes"))}
    subs = {}
    for n, s in supers.items():
        if s:
            subs.setdefault(s, []).append(n)
    parts = [_GENERATED % "src/ast/*.yaml", """\
# The curated model

What a rule reads when it matches a model kind (`match: { kind: Class }`).
Every class, with its base, its subclasses and its fields; a field of a
base is readable on every subclass (`node.name` on a `Class` is `Decl`'s).
Each field gives the type the rule checker sees: a class name, `list(T)`,
`bool`, `string`, `int`, `double`. An enum is an `int`, compared with its
values by name (`node.kind == SubroutineKind.Task`). A field of class type
can be null: guard it (`node.base != null && ...`). `--check-rules` refuses a
field that does not exist, at its column.

Search this file for a class (`## Call`) or a field (`- \\`subroutine\\``).

"""]
    for stem, sec in model:
        for name, body in _entries(sec.get("enums")):
            parts.append("## enum %s\n\n%s\n\n" % (name, _public(body.get("doc", "").strip())))
            for v in body.get("values") or []:
                (vn, vd), = v.items()
                parts.append("- `%s.%s`: %s\n" % (name, vn, _public(vd)))
            parts.append("\n")
        for name, body in _entries(sec.get("structs")):
            desc, _ = _split_doc(body.get("doc"))
            parts.append("## struct %s\n\n%s\n\n" % (name, desc))
            for fld, spec in _fields(body):
                parts.append("- `%s`: %s\n" % (fld, _plain_type(spec.get("type", ""), enums)))
            parts.append("\n")
        for name, body in _entries(sec.get("classes")):
            desc, attrs = _split_doc(body.get("doc"))
            head = "## %s\n\n" % name
            rel = []
            if body.get("super"):
                rel.append("extends `%s`" % body["super"])
            if subs.get(name):
                rel.append("subclasses: " + ", ".join("`%s`" % s for s in subs[name]))
            if body.get("set_by") == "classify":
                rel.append("made by the classify stage (contexts)")
            parts.append(head + ("*%s.*\n\n" % "; ".join(rel) if rel else "") + desc + "\n\n")
            for fld, spec in _fields(body):
                t = types.get((name, fld))
                tt = "not readable by a rule" if t is None else "`%s`" % t
                if t == "int":
                    e = _plain_type(spec.get("type", ""), enums)
                    if e in enums:
                        tt = "`int` (enum `%s`)" % e
                note = attrs.get(fld, "")
                parts.append("- `%s` %s%s\n" % (fld, tt, (": " + note) if note else ""))
            parts.append("\n")
    return "".join(parts).rstrip("\n") + "\n"


def _plain_type(t, enums):
    t = re.sub(r"\bU?P<(\w+)>", r"\1", str(t))
    t = re.sub(r"list<(.+)>", r"list(\1)", t)
    return {"int32_t": "int", "int64_t": "int"}.get(t, t)


