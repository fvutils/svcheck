def render_syntax() -> str:
    from gen_syntax_schema import cpp, parse
    types, order, _ = parse(str(SYNTAX_TXT))
    parts = [_GENERATED % "slang's scripts/syntax.txt", """\
# slang's syntax kinds

The syntax layer: every file as parsed, with macros expanded. Each entry is
a syntax *type* (`match: { kind: CaseStatementSyntax }` matches every kind
of the type) with its base, its *kinds* (`match: { kind: CaseStatement }`
is exactly one) and its fields, as a rule reads them:

- `token`: a `Token` (`text`, `raw`, `kind`, `missing`, `line`, `col`), or
  **null when the source has no such token**: test `!= null` first;
- `tokenlist`: a list of `Token`;
- `T` / `T?`: one node of type `TSyntax` (`T?` may be null);
- `list<T>`: a list of nodes (a separated list's commas are left out).

A field of a base type is readable on the derived types. Find a construct
by its keyword or name: `grep -n 'Case' syntax-kinds.md`.

"""]
    for name in order:
        t = types[name]
        head = "## %s" % cpp(name)
        if t.base and t.base != "SyntaxNode":
            head += " (extends %s)" % cpp(t.base)
        parts.append(head + "\n\n")
        if t.kinds:
            parts.append("kinds: " + ", ".join(sorted(t.kinds)) + "\n\n")
        fields = []
        for m in t.members:
            if m.kind in ("token", "tokenlist"):
                fields.append("`%s` %s" % (m.name, m.kind))
            elif m.kind == "node":
                fields.append("`%s` %s%s" % (m.name, m.elem, "?" if m.optional else ""))
            else:
                fields.append("`%s` list<%s>" % (m.name, m.elem))
        if fields:
            parts.append("fields: " + "; ".join(fields) + "\n\n")
    return "".join(parts).rstrip("\n") + "\n"


# ---------------------------------------------------------------------------

def render_all(hooks):
    """{file name: text} for every generated reference."""
    model = _model()
    reg = hooks.cel_functions()
    return {
        "model.md": render_model(model, field_types(hooks, model)),
        "functions.md": render_functions(reg["functions"], reg["records"]),
        "uvm-helpers.md": render_uvm_helpers(),
        "syntax-kinds.md": render_syntax(),
    }


def main() -> int:
    from hooks import EngineHooks
    h = EngineHooks(semantic="model")
    try:
        files = render_all(h)
    finally:
        h.close()
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (OUT_DIR / name).write_text(text, encoding="utf-8")
        print("wrote %s" % (OUT_DIR / name).relative_to(_ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
