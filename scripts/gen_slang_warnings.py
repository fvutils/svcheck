#!/usr/bin/env python3
"""slang's warnings as svcheck markers (svcheck-plan P2.3; Q-UVM4, decided 2026-10-17).

Each warning option of slang's `scripts/diagnostics.txt` is a marker `SLANG###` whose name is
the option's (`unused-variable`). The numbers are svcheck's, kept in an append-only table,
`src/host/slang_warnings.txt` ("NNN name" per line): a number is never reused or changed, so
a waiver or config that names one stays right across slang versions.

  gen_slang_warnings.py --update DIAGNOSTICS TABLE
      appends the options DIAGNOSTICS has and TABLE lacks, numbered from the last + 1
  gen_slang_warnings.py DIAGNOSTICS TABLE OUT.cpp
      writes the table the host installs (`SlangWarnings.h`): per marker its number, name,
      whether slang's `default` group has it (tier `suspicious`, else `pedantic`), and a
      summary from slang's message. Fails when DIAGNOSTICS has an option TABLE lacks (run
      --update after a slang bump). An option slang no longer has stays, marked removed.
"""
import re
import sys


def read_diagnostics(path):
    """(options in file order with their first message, the default group's options)."""
    opts = {}
    order = []
    groups = {}
    text = open(path, encoding="utf-8").read()
    for m in re.finditer(r'^warning\s+(\S+)\s+\S+\s+"((?:[^"\\]|\\.)*)"', text, re.M):
        name, msg = m.group(1), m.group(2)
        if name not in opts:
            opts[name] = msg
            order.append(name)
    for m in re.finditer(r'^group\s+(\S+)\s*=\s*\{([^}]*)\}', text, re.M):
        groups[m.group(1)] = m.group(2).split()
    return order, opts, set(groups.get("default", []))


def read_table(path):
    rows = []
    try:
        lines = open(path, encoding="utf-8").read().splitlines()
    except FileNotFoundError:
        return rows
    for line in lines:
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        num, name = line.split()
        rows.append((int(num), name))
    return rows


def summary(msg):
    """slang's message as a summary: its arguments are "…"."""
    s = msg.encode().decode("unicode_escape")
    s = re.sub(r"\{[^}]*\}", "…", s)
    return s[:1].upper() + s[1:]


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def update(diag, table):
    order, _, _ = read_diagnostics(diag)
    rows = read_table(table)
    have = {name for _, name in rows}
    nxt = max((n for n, _ in rows), default=0) + 1
    added = []
    for name in order:
        if name not in have:
            added.append((nxt, name))
            nxt += 1
    if nxt > 1000:
        sys.exit("gen_slang_warnings: more than 999 SLANG numbers")
    with open(table, "a", encoding="utf-8") as fp:
        if not rows:
            fp.write("# slang's warning options as svcheck markers SLANG### (svcheck-plan P2.3,\n"
                     "# Q-UVM4). Append-only: a number is never reused or changed. Grown by\n"
                     "# scripts/gen_slang_warnings.py --update after a slang bump.\n")
        for num, name in added:
            fp.write("%03d %s\n" % (num, name))
    print("gen_slang_warnings: %d added" % len(added))


def generate(diag, table, out):
    order, opts, default = read_diagnostics(diag)
    rows = read_table(table)
    have = {name for _, name in rows}
    missing = [n for n in order if n not in have]
    if missing:
        sys.exit("gen_slang_warnings: %s has warnings %s has not: %s (run "
                 "scripts/gen_slang_warnings.py --update)" % (diag, table, ", ".join(missing)))
    lines = [
        "// Generated by scripts/gen_slang_warnings.py from slang's diagnostics.txt and",
        "// src/host/slang_warnings.txt. Do not edit.",
        '#include "SlangWarnings.h"',
        "",
        "namespace svcheck {",
        "namespace host {",
        "",
        "const SlangWarningInfo *slangWarnings() {",
        "    static const SlangWarningInfo table[] = {",
    ]
    for num, name in rows:
        removed = name not in opts
        lines.append("        {%d, %s, %s, %s, %s}," % (
            num, cstr(name), "true" if name in default else "false",
            "true" if removed else "false", cstr("" if removed else summary(opts[name]))))
    lines += [
        "        {0, nullptr, false, false, nullptr},",
        "    };",
        "    return table;",
        "}",
        "",
        "}",
        "}",
        "",
    ]
    text = "\n".join(lines)
    try:
        if open(out, encoding="utf-8").read() == text:
            return
    except FileNotFoundError:
        pass
    with open(out, "w", encoding="utf-8") as fp:
        fp.write(text)


def main(argv):
    if len(argv) == 3 and argv[0] == "--update":
        update(argv[1], argv[2])
    elif len(argv) == 3:
        generate(*argv)
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main(sys.argv[1:])
