def _title(fn):
    from gen_rule_functions import _title as t
    return t(fn)


def render_functions(functions, records=None) -> str:
    functions = [f for f in functions if f["in_profile"]]
    parts = [_GENERATED % "the rule engine's function registry", """\
# Functions

Every operator, function and macro a rule expression can use. The groups
before *Kind tests* are standard CEL; from *Kind tests* on they are
svcheck's library over the syntax trees and the model. `node` is any node;
a model class name (`Class`, `Stmt`) is that class or a subclass. A
function that names a model class exists only with the model (the default).
A receiver function is written `x.f(...)`, the others `f(x, ...)`.

"""]
    groups = []
    for f in functions:
        if f["group"] not in groups:
            groups.append(f["group"])
    for g in groups:
        parts.append("## %s\n\n" % g)
        names = []
        for f in functions:
            if f["group"] == g and f["function"] not in names:
                names.append(f["function"])
        for n in names:
            ovs = [f for f in functions if f["group"] == g and f["function"] == n]
            parts.append("### `%s`\n\n" % _title(n))
            docs = []
            for f in ovs:
                if f["doc"] not in docs:
                    docs.append(f["doc"])
            for f in ovs:
                parts.append("- `%s`\n" % f["display"])
            parts.append("\n" + "\n\n".join(_public(d) for d in docs if d) + "\n\n")
    for r in records or []:
        parts.append("## record %s\n\n%s\n\n" % (r["name"], _public(r["doc"])))
        for m in r["members"]:
            parts.append("- `%s` `%s`: %s\n" % (m["name"], m["type"], _public(m["doc"])))
        parts.append("\n")
    return "".join(parts).rstrip("\n") + "\n"


