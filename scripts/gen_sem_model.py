#!/usr/bin/env python3
"""Generate the curated SV model's C++ from ``src/ast/*.yaml``.

svcheck-plan P1.3; svcheck-design §3.6. Runs pyastbuilder's ``gen-cpp`` (the
classes, in namespace ``svcheck::sem``) and ``gen-reflect`` (the tables the
rule engine reads) into OUT_DIR:

- ``OUT_DIR/include/svcheck/sem/I*.h``: the interfaces, which the lowering
  pass (``src/lower``) and the host include;
- ``OUT_DIR/*.{h,cpp}``: the implementation classes and the factory;
- ``OUT_DIR/reflect/Reflect.cpp``: the class, field, enum and struct tables;
- ``OUT_DIR/pyext/``: the ``svcheck.sem`` Cython module (``gen-pyext``;
  svcheck-plan P2.6b), which setup.py copies into ``python/svcheck/``.

The module loads ``libsvcheck`` (``-libname``), which holds the model and
exports ``sem_getFactory``. Every node wrapper carries gen-pyext's
``_owner``: ``svcheck.core`` sets it to the ``Compilation`` on the root it
hands out, and every node reached from there gets it, so no wrapper outlives
the model. Both need pyastbuilder 0.0.9.

gen-reflect also writes a ``Reflect.h`` that declares its own ``Node``,
``Value`` and table types. The engine has the same types already
(``src/engine/schema/Reflect.h``, which was copied from that interface), and
the two must be one, so this script replaces the generated header with a shim
that takes the engine's types into ``svcheck::sem::reflect`` and declares the
tables. The host merges them with the syntax schema's at install time
(``src/host/Schema.cpp``); the curated classes keep ids 1..NumClasses.

pyastbuilder is imported from ``packages/pyastbuilder/src`` when that exists,
as pssparser's ``scripts/gen_ast.py`` does.

Usage: gen_sem_model.py AST_DIR OUT_DIR [PACKAGES_DIR]

Files are written only when they change, so a re-run does not force a rebuild.
"""
import filecmp
import os
import re
import shutil
import subprocess
import sys
import tempfile

SHIM = """\
/*
 * Reflect.h -- GENERATED by scripts/gen_sem_model.py. Do not edit.
 *
 * The curated model's reflection tables (pyastbuilder gen-reflect), declared
 * with the rule engine's types: gen-reflect's own header is replaced by this
 * one, so Reflect.cpp builds against src/engine/schema/Reflect.h.
 */
#pragma once
#include <stdint.h>
#include <string>
#include "schema/Reflect.h"

namespace svcheck {
namespace sem {
class ISemNode;
namespace reflect {

using svcheck::ast::reflect::ClassInfo;
using svcheck::ast::reflect::EnumInfo;
using svcheck::ast::reflect::FieldInfo;
using svcheck::ast::reflect::FieldType;
using svcheck::ast::reflect::Node;
using svcheck::ast::reflect::StructFieldInfo;
using svcheck::ast::reflect::StructInfo;
using svcheck::ast::reflect::Value;

/** Number of classes. Class ids are 1..NumClasses; 0 is "no node". */
constexpr uint16_t NumClasses = %(num)d;

extern const ClassInfo classes[NumClasses + 1];     // [0] is "no node"
extern const FieldInfo fields[];
extern const uint16_t  numFields;
extern const EnumInfo  enums[];
extern const uint16_t  numEnums;
extern const StructInfo structs[];
extern const uint16_t  numStructs;

/** The handle of a node: its own class id, and the node as that class. */
Node classify(ISemNode *n);
/** The node a handle refers to, as the root interface; null for another schema's node. */
ISemNode *asSemNode(const Node &n);

uint32_t listSize(const Value &list);
Value listAt(const Value &list, uint32_t idx);

} // namespace reflect
} // namespace sem
} // namespace svcheck
"""


def run(cmd, env, cwd):
    r = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, env=env, text=True,
                       cwd=cwd)
    if r.returncode != 0:
        sys.stderr.write(r.stdout)
        raise SystemExit("gen_sem_model.py: failed: %s" % " ".join(cmd))


def sync(src, dst):
    """Copy the tree src over dst: changed and new files only; remove the rest."""
    keep = set()
    for d, _, files in os.walk(src):
        rel = os.path.relpath(d, src)
        os.makedirs(os.path.join(dst, rel), exist_ok=True)
        for f in files:
            s = os.path.join(d, f)
            t = os.path.normpath(os.path.join(dst, rel, f))
            keep.add(t)
            if not os.path.exists(t) or not filecmp.cmp(s, t, shallow=False):
                shutil.copyfile(s, t)
    for d, _, files in os.walk(dst):
        for f in files:
            t = os.path.normpath(os.path.join(d, f))
            if t not in keep:
                os.remove(t)


def main(argv):
    if len(argv) not in (3, 4):
        sys.stderr.write(__doc__)
        return 2
    ast_dir = os.path.abspath(argv[1])
    out_dir = os.path.abspath(argv[2])
    env = os.environ.copy()
    if len(argv) == 4:
        src = os.path.join(argv[3], "pyastbuilder", "src")
        if os.path.isdir(src):
            env["PYTHONPATH"] = os.pathsep.join(
                [src] + ([env["PYTHONPATH"]] if env.get("PYTHONPATH") else []))

    with tempfile.TemporaryDirectory() as tmp:
        cpp = os.path.join(tmp, "out")
        refl = os.path.join(cpp, "reflect")
        # In the temporary directory: pyastbuilder 0.0.8's gen-cpp makes an
        # empty `${CMAKE_CURRENT_SOURCE_DIR}/include/...` tree in its working
        # directory (gen_cpp.py's install rule; fixed after 0.0.8). Keep this
        # while the PyPI release is 0.0.8.
        run([sys.executable, "-m", "astbuilder", "gen-cpp", "-astdir", ast_dir,
             "-o", cpp, "-namespace", "svcheck::sem", "-name", "sem"], env, tmp)
        run([sys.executable, "-m", "astbuilder", "gen-reflect", "-astdir", ast_dir,
             "-o", refl, "-namespace", "svcheck::sem"], env, tmp)
        # Not used: svcheck builds the sources into its own target.
        os.remove(os.path.join(cpp, "CMakeLists.txt"))
        pyext = os.path.join(cpp, "pyext")
        run([sys.executable, "-m", "astbuilder", "gen-pyext", "-astdir", ast_dir,
             "-o", pyext, "-namespace", "svcheck::sem", "-name", "sem",
             "-package", "svcheck.sem", "-libname", "svcheck"], env, tmp)

        with open(os.path.join(refl, "Reflect.h"), encoding="utf-8") as fp:
            m = re.search(r"constexpr uint16_t NumClasses = (\d+);", fp.read())
        if not m:
            raise SystemExit("gen_sem_model.py: no NumClasses in gen-reflect's Reflect.h")
        with open(os.path.join(refl, "Reflect.h"), "w", encoding="utf-8") as fp:
            fp.write(SHIM % {"num": int(m.group(1))})
        sync(cpp, out_dir)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
