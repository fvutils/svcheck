#!/usr/bin/env python3
"""Generate the syntax schema's tables from slang's ``scripts/syntax.txt``.

svcheck-plan P1.2; svcheck-design §3.2. Writes a C++ source with the class
and field tables the rule engine reads (``src/engine/schema/Reflect.h``,
gen-reflect's layout) for slang's syntax tree, and the map between slang's
``SyntaxKind`` and the class ids. It is compiled into the SV host
(``src/host``), which installs it.

The classes:

- ``SyntaxNode``, the root (class 1);
- one per syntax type, named as slang's C++ type (``ClassDeclarationSyntax``,
  ``ExpressionSyntax``), with the type's members as fields and its base type
  as super class;
- one per ``SyntaxKind`` (``ClassDeclaration``, ``AddExpression``), a
  subclass of the type that holds it, with no fields of its own.

A node's class is its kind's. So ``match: ClassDeclaration`` is one kind,
and ``match: BinaryExpressionSyntax`` is every kind in the type's
``kindmap`` group, through the super chain.

The fields, by syntax.txt member type:

- ``token``: a ``Token`` struct (the host's, struct 0); null when the token
  is absent;
- ``tokenlist``: a list of ``Token``;
- ``T`` and ``T?``: an owned node of class ``TSyntax`` (null when unset);
- ``list<T>``, ``separated_list<T>``: a list of owned nodes; a separated
  list's separators are tokens and are left out.

Usage: gen_syntax_schema.py SYNTAX_TXT OUT.cpp

The output is written only when it changes, so a re-run does not force a
rebuild.
"""
