def render_uvm_helpers() -> str:
    """rules/uvm.yaml's `define:` block, each helper with its comment."""
    lines = UVM_YAML.read_text(encoding="utf-8").splitlines()
    start = next(i for i, x in enumerate(lines) if x.strip() == "define:")
    indent = len(lines[start]) - len(lines[start].lstrip()) + 2
    parts = [_GENERATED % "rules/uvm.yaml", """\
# The UVM helpers (`uses: [uvm.yaml]`)

The built-in helper file `uvm.yaml` holds the vocabulary of svcheck's UVM
pack. A rule file names it with `uses: [uvm.yaml]` (a bare name with no
such file beside the rule file is the built-in one), and every rule of the
file can then call these helpers as functions. Use them rather than
writing your own: `is_component(cls(node))`, `config_db(node)`,
`factory_create(node)`. A comment line (`# ----`) starts a group.
`uses:` also brings the file's content classifiers (`unit` axis: `agent`,
`env`, `test`, `tb-top`, `seq-lib`, `regmodel`, `base-lib`) into a run of
the file's rules, for `applies_to: { unit: agent }`.

"""]
    comment, i = [], start + 1
    while i < len(lines):
        x = lines[i]
        ind = len(x) - len(x.lstrip())
        if x.strip() and ind < indent:
            break
        s = x.strip()
        if s.startswith("# ----"):
            # A group: its title is the comment's first sentence.
            group = [s[len("# ----"):].strip()]
            while i + 1 < len(lines) and lines[i + 1].strip().startswith("#"):
                i += 1
                group.append(lines[i].strip().lstrip("#").strip())
            title = _public(" ".join(group)).split(". ")[0].rstrip(".")
            parts.append("\n## %s\n\n" % title)
            comment = []
        elif s.startswith("#"):
            comment.append(s.lstrip("#").strip())
        elif ind == indent and s:
            key, _, val = s.partition(": ")
            if not val:
                key, val = s.rstrip(":"), ""
            body = [] if val in (">-", "|", "") else [val.strip("'\"")]
            j = i + 1
            while j < len(lines) and lines[j].strip() and \
                    len(lines[j]) - len(lines[j].lstrip()) > indent:
                body.append(lines[j].strip())
                j += 1
            text = _public(" ".join(c for c in comment if c))
            parts.append("- `%s`%s\n  ```\n  %s\n  ```\n" % (
                key, (": " + text) if text else "", "\n  ".join(body)))
            comment = []
            i = j
            continue
        i += 1
    return "".join(parts).rstrip("\n") + "\n"


